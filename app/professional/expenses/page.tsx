"use client"

import { useEffect, useState } from "react"
import { useRouter } from "next/navigation"
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Label } from "@/components/ui/label"
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select"
import { Badge } from "@/components/ui/badge"
import { Plus, Trash2, ArrowLeft, Filter, DollarSign, Calendar as CalendarIcon, Briefcase } from "lucide-react"
import { AppHeader } from "@/components/app-header"
import { toast } from "sonner"
import type { Job } from "@/app/professional/jobs/page"

export type Expense = {
  id: string
  professionalId: string
  name: string
  category: "materials" | "transportation" | "miscellaneous"
  amount: number
  date: string
  relatedJobId?: string
  relatedJobName?: string
  notes?: string
  autoGenerated?: boolean
}

